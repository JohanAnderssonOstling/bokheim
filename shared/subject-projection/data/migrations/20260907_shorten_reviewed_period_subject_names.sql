CREATE TEMP TABLE rename_guard(ok INTEGER CHECK(ok=1));
INSERT INTO rename_guard SELECT count(*)=323 FROM reviewed_rename r JOIN concept c USING(concept_id)
 WHERE c.preferred_label IN (r.old_label,r.new_label);
INSERT INTO source_label(concept_id,label,ordinal)
 SELECT r.concept_id,r.old_label,coalesce((SELECT max(s.ordinal)+1 FROM source_label s WHERE s.concept_id=r.concept_id),0)
 FROM reviewed_rename r WHERE NOT EXISTS(SELECT 1 FROM source_label s WHERE s.concept_id=r.concept_id AND s.label=r.old_label);
UPDATE concept SET preferred_label=(SELECT new_label FROM reviewed_rename WHERE concept_id=concept.concept_id)
 WHERE concept_id IN (SELECT concept_id FROM reviewed_rename);
