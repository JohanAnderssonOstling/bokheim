pub(crate) fn export_bindings(path: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let path = path.as_ref();
    builder().export(Typescript::default(), path)?;
    let generated = std::fs::read_to_string(path)?;
    std::fs::write(path, format!("{}\n", generated.trim_end()))?;
    Ok(())
}
