#!/usr/bin/env python3
"""Generate named regional and local-place detail for the History hierarchy."""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
HISTORY_PATH = HERE / "generate-exhaustive-history-lcc-migration.py"
SPEC = importlib.util.spec_from_file_location("history_locality_core", HISTORY_PATH)
assert SPEC and SPEC.loader
history = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = history
SPEC.loader.exec_module(history)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--taxonomy",
        type=Path,
        default=Path("client/library-model/data/unified-taxonomy-v2.sqlite3"),
    )
    parser.add_argument(
        "--snapshot",
        type=Path,
        default=Path("client/library-model/data/lcc-mdsconnect-2016.sqlite3"),
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("client/library-model/data/history-lcc-localities-manifest.json"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("client/library-model/data/migrations/20260817_history_lcc_localities.sql"),
    )
    args = parser.parse_args()

    manifest = history.build_manifest(
        args.taxonomy,
        args.snapshot,
        include_localities=True,
    )
    manifest["scope"] = "named regions, administrative divisions, cities, towns, and localities"
    args.manifest.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    sql = history.render_sql(manifest, args.taxonomy).replace(
        "Exhaustive semantic LCC continuation beneath the curated History hierarchy.",
        "Named regional and local-place continuation beneath the curated History hierarchy.",
    ).replace(
        "Catalog forms and authority/filing trees remain in the source snapshot only.",
        "Named places are retained; catalog forms, people, institutions, and filing containers remain excluded.",
    ).replace(
        "Generated by scripts/generate-exhaustive-history-lcc-migration.py.",
        "Generated by scripts/generate-history-lcc-localities-migration.py.",
    )
    args.output.write_text(sql, encoding="utf-8")
    print(json.dumps({
        "eligible_snapshot_records": manifest["eligible_snapshot_records"],
        "represented_snapshot_records": manifest["represented_snapshot_records"],
        "assigned_snapshot_records": manifest["assigned_snapshot_records"],
        "new_nodes": len(manifest["new_nodes"]),
        "edges": len(manifest["edges"]),
        "selectors": len(manifest["selectors"]),
        "collapsed_same_span_records": manifest["collapsed_same_span_records"],
        "transparent_structural_records": manifest["transparent_structural_records"],
        "reused_direct_children": manifest["reused_direct_children"],
        "excluded": {key: value["count"] for key, value in manifest["excluded"].items()},
    }, indent=2))


if __name__ == "__main__":
    main()
